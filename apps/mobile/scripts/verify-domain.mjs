import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';
const require = createRequire(import.meta.url), ts = require('typescript');
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..'), cache = new Map();
function load(file) {
  if (cache.has(file)) return cache.get(file).exports;
  const module = { exports: {} }; cache.set(file,module);
  const source = ts.transpileModule(readFileSync(file,'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
  vm.runInThisContext(`(function(exports,require,module){${source}\n})`, { filename: file })(module.exports, path => path.startsWith('.') ? load(resolve(dirname(file),path+'.ts')) : require(path), module);
  return module.exports;
}
const { categories } = load(resolve(root,'src/domain/catalog.ts'));
const web = load(resolve(root,'../../src/features/customer/config.ts'));
assert.deepEqual(categories.map(({icon,...category})=>category), [...web.customerCategories]);
const { parsePreview } = load(resolve(root,'src/domain/preview.ts'));
const { createPreviewStore, PREVIEW_KEY } = load(resolve(root,'src/data/store-core.ts'));
let saved=null, writes=0;
const port={getItem:async()=>saved,setItem:async(key,value)=>{assert.equal(key,PREVIEW_KEY);writes++;saved=value;}};
const store=createPreviewStore(port);await store.hydrate();
assert.equal(writes,0,'Opening an empty preview does not write data');
const first=await store.saveStarter('plumbing');
await store.setMode('provider');
assert.equal(parsePreview(saved).mode,'provider');
const restarted=createPreviewStore(port);await restarted.hydrate();assert.equal(restarted.getSnapshot().data.mode,'provider');assert.equal(restarted.getSnapshot().data.starters[0].id,first.id);
await restarted.saveStarter('electrical',first.id);assert.equal(restarted.getSnapshot().data.starters.length,1);assert.equal(restarted.getSnapshot().data.starters[0].createdAt,first.createdAt);
await Promise.all([restarted.setMode('customer'),restarted.saveStarter('cleaning')]);
assert.equal(parsePreview(saved).mode,'customer');assert.equal(parsePreview(saved).starters.length,2);
await restarted.removeStarter(first.id);assert.equal(parsePreview(saved).starters.length,1);
assert.throws(()=>restarted.setMode('admin'));await assert.rejects(restarted.saveStarter('carpentry'));await assert.rejects(restarted.saveStarter('plumbing','missing-id'));
for(const value of ['{broken',JSON.stringify({schemaVersion:2,mode:'customer',starters:[]}),JSON.stringify({schemaVersion:1,mode:'admin',starters:[]})])assert.throws(()=>parsePreview(value));
let attempted=0;
